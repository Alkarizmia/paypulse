export function getDashboardViewCopy(locale: AppLocale): DashboardViewCopy {
  return PACKS[locale] as DashboardViewCopy;
}

/** Remplace `{name}` dans les chaînes de notification. */
export function withName(template: string, name: string): string {
  return template.replaceAll("{name}", name);
}
